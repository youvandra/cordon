/**
 * Record Circle's x402 catalogue, read from the discovery API.
 *
 * The landing page and the docs quote this catalogue — how many services
 * agents can buy, what a typical offer costs, how many are on Arc — and every
 * one of those numbers was typed by hand from a sample taken on 8 September.
 * A figure somebody typed is a figure that goes stale without anybody noticing,
 * which is the defect this repository has a rule against. So the catalogue is
 * walked, every page of it, and the file is written by the walk.
 *
 *   node packages/fixtures/scripts/record-marketplace.mjs
 *
 * It reads no key and needs no package: the API is public and uncredentialed,
 * and `fetch` is Node's own.
 *
 * Every figure written here has one definition, stated beside it. A figure
 * this script cannot define is not written — which is why the hand-typed
 * `gatewayCapable`, `sampled`, `priceMin` and `priceMax` are gone: nothing
 * rendered them, and one of them had no definition anybody could reproduce.
 */
import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../src/marketplace.gen.ts");
const DISCOVERY = "https://api.circle.com/v2/x402/discovery/resources";
const ARC = "eip155:5042002";
const PAGE = 100;

/* Every page, by offset, until the API's own total is reached. A walk that
   stopped at the first page would print a catalogue fifty resources long. */
const items = [];
let total;
for (let offset = 0; ; ) {
  const url = `${DISCOVERY}?limit=${PAGE}&offset=${offset}`;
  const response = await fetch(url, { headers: { accept: "application/json" } });
  if (!response.ok) throw new Error(`discovery answered ${response.status} at offset ${offset}`);
  const body = await response.json();
  const page = body.items ?? [];
  items.push(...page);
  total = Number(body.pagination?.total ?? items.length);
  offset += page.length;
  if (page.length === 0 || offset >= total) break;
  await new Promise((done) => setTimeout(done, 300));
}

if (items.length !== total) {
  throw new Error(`walked ${items.length} resources and the API reports ${total}; refusing to write a partial catalogue`);
}

const offers = items.flatMap((item) => item.accepts ?? []);

/* A price is `amount` in base units. Every offer in the catalogue names a
   USDC-family token with six decimals; an amount that does not parse is a
   reason to stop, not to skip, because a median over the parsable half is a
   different number. */
const prices = offers.map((offer) => {
  const amount = Number.parseInt(offer.amount, 10);
  if (!Number.isFinite(amount)) throw new Error(`unparsable amount ${JSON.stringify(offer.amount)} on ${offer.network}`);
  return amount / 1e6;
});
const sorted = [...prices].sort((a, b) => a - b);
const middle = Math.floor(sorted.length / 2);
const median = sorted.length % 2 ? sorted[middle] : (sorted[middle - 1] + sorted[middle]) / 2;

const figures = {
  /** Resources in the catalogue — each one a thing an agent can buy. */
  services: items.length,
  /** Price offers across those resources; one resource can offer several. */
  offersTotal: offers.length,
  /** Offers priced at one cent or less. */
  offersAtOrBelowOneCent: prices.filter((price) => price <= 0.01).length,
  /** Median offer price, in dollars. */
  priceMedian: Number(median.toFixed(6)),
  /** Most expensive single offer, in dollars. */
  priceMax: Number(sorted[sorted.length - 1].toFixed(6)),
  /** Offers whose token is named `GatewayWalletBatched` — settled through Circle's Gateway. */
  gatewayBatchedOffers: offers.filter((offer) => offer.extra?.name === "GatewayWalletBatched").length,
  /** Offers payable on Arc, the chain Cordon's vault is on. */
  arcListings: offers.filter((offer) => offer.network === ARC).length,
};

const recordedAt = new Date().toISOString();
const byNetwork = {};
for (const offer of offers) byNetwork[offer.network] = (byNetwork[offer.network] ?? 0) + 1;
const topNetworks = Object.entries(byNetwork).sort((a, b) => b[1] - a[1]).slice(0, 6);

writeFileSync(
  out,
  `// GENERATED by packages/fixtures/scripts/record-marketplace.mjs — do not edit.\n` +
    `// Walked every page of Circle's x402 discovery API on ${recordedAt.slice(0, 10)}.\n` +
    `// Largest networks by offer count: ${topNetworks.map(([n, c]) => `${n} ${c}`).join(", ")}.\n\n` +
    `export const MARKETPLACE = ${JSON.stringify(
      { discovery: DISCOVERY, recordedAt, ...figures },
      null,
      2,
    )} as const;\n`,
);

console.log(`marketplace -> ${out}`);
console.log(JSON.stringify(figures, null, 2));
