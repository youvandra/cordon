/**
 * Runs G7 and writes what it produced into packages/fixtures/src/eval.gen.ts,
 * plus the gate row itself.
 *
 * Two things have to be true for G7 to be green, and they are different
 * claims: the suite around the run passes, and the run's own verdict is that
 * the work got through. A green suite with a blocked brief is exactly the
 * result this gate exists to be able to report, so it may not be hidden behind
 * a passing test count.
 *
 * Usage: node scripts/record-eval.mjs
 */
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { writeGate } from "../../contracts/scripts/gates.mjs";
import { runEval } from "../src/run.ts";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../fixtures/src/eval.gen.ts");

/* Named rather than globbed: execFileSync runs no shell, so a pattern would
   reach node as a literal path and the run would fail as a missing module —
   which is a red gate for a reason that has nothing to do with the product. */
const testDir = resolve(here, "../test");
const tests = readdirSync(testDir).filter((f) => f.endsWith(".test.ts")).map((f) => `test/${f}`);

let tap = "";
let suiteFailed = false;
try {
  tap = execFileSync("node", ["--test", "--test-reporter=tap", ...tests], {
    cwd: resolve(here, ".."),
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
    timeout: 30 * 60 * 1000,
  });
} catch (e) {
  tap = e.stdout ?? "";
  suiteFailed = true;
}

const count = (label) => Number(tap.match(new RegExp(`^# ${label} (\\d+)$`, "m"))?.[1] ?? 0);
const passed = count("pass");
const failed = count("fail");
const total = passed + failed;
if (total === 0) suiteFailed = true;

const result = await runEval({ runs: Number(process.env.CORDON_EVAL_RUNS ?? 3) });

const json = (v) => JSON.stringify(v);
const bigint = (v) => `${v.toString()}n`;

const condition = (c) =>
  `  {\n` +
  `    id: ${json(c.id)},\n` +
  `    runs: ${c.runs},\n` +
  `    completed: ${c.completed},\n` +
  `    unsupported: ${c.unsupported},\n` +
  `    spent6: ${bigint(c.spent6)},\n` +
  `    refusals: ${c.refusals},\n` +
  `    exposureAtStart6: ${bigint(c.exposureAtStart6)},\n` +
  `    chainWrites: ${c.chainWrites},\n` +
  `    writesPerPurchase: ${c.writesPerPurchase},\n` +
  `  },`;

writeFileSync(
  out,
  `// GENERATED by packages/eval/scripts/record-eval.mjs from the G7 run\n` +
    `// itself. Do not edit: every number here is what the run produced.\n\n` +
    `export type EvalCondition = {\n` +
    `  /** "cordon" or "shared-cap". */\n  id: string;\n` +
    `  runs: number;\n` +
    `  /** Briefs that met the acceptance criteria, out of \`runs\`. */\n  completed: number;\n` +
    `  /** Sources cited with a body no seller served. Must be zero. */\n  unsupported: number;\n` +
    `  spent6: bigint;\n` +
    `  refusals: number;\n` +
    `  /** USDC out of the owner's hands before any work was done. */\n  exposureAtStart6: bigint;\n` +
    `  chainWrites: number;\n` +
    `  writesPerPurchase: number;\n` +
    `};\n\n` +
    `export type EvalRunRecord = {\n` +
    `  /** Which agent produced the briefs. Never implied. */\n  agent: string;\n` +
    `  runs: number;\n` +
    `  sources: number;\n` +
    `  window6: bigint;\n` +
    `  taskCost6: bigint;\n` +
    `  conditions: EvalCondition[];\n` +
    `  verdict: "work-gets-through" | "the-fence-blocks-the-work";\n` +
    `  tests: number;\n` +
    `  passed: number;\n` +
    `  recordedAt: string;\n` +
    `};\n\n` +
    `export const EVAL: EvalRunRecord = {\n` +
    `  agent: ${json(result.agent)},\n` +
    `  runs: ${result.runs},\n` +
    `  sources: ${result.sources},\n` +
    `  window6: ${bigint(result.window6)},\n` +
    `  taskCost6: ${bigint(result.taskCost6)},\n` +
    `  conditions: [\n${result.conditions.map(condition).join("\n")}\n  ],\n` +
    `  verdict: ${json(result.verdict)},\n` +
    `  tests: ${total},\n` +
    `  passed: ${passed},\n` +
    `  recordedAt: ${json(result.recordedAt)},\n` +
    `};\n`,
);

const green = !suiteFailed && passed === total && result.verdict === "work-gets-through";
writeGate({
  id: "G7",
  status: green ? "green" : "red",
  tests: total,
  passed,
  recordedAt: result.recordedAt,
});

console.log(`G7: ${green ? "green" : "red"} — ${passed}/${total} tests, verdict ${result.verdict}`);
process.exit(green ? 0 : 1);
