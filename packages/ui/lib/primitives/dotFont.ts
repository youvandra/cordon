export interface DotLayout {
  /** Circle centres, in the returned viewBox's own units. */
  dots: { cx: number; cy: number }[];
  width: number;
  height: number;
  /** Characters with no glyph in the face. */
  missing: string[];
}

export interface DotLayoutOptions {
  /** Column pitch. The stage uses 4 for words, 5 for numerals. */
  pitchX?: number;
  /** Row pitch. Always 4 on the stage. */
  pitchY?: number;
  /** Columns of air between glyphs. */
  gap?: number;
}

/**
 * Lay a string out as dot centres. Pure — no DOM, so it can be measured,
 * snapshot-tested, or rendered to canvas just as easily as to SVG.
 */
export function layoutDots(
  text: string,
  { pitchX = 5, pitchY = 4, gap = 1 }: DotLayoutOptions = {},
): DotLayout {
  const dots: { cx: number; cy: number }[] = [];
  const missing: string[] = [];
  let x = 0;

  for (const char of text) {
    const glyph = DOT_GLYPHS[char];
    if (!glyph) {
      missing.push(char);
      continue;
    }
    const cols = glyph[0].length;
    glyph.forEach((row, y) => {
      for (let col = 0; col < row.length; col++) {
        if (row[col] !== "1") continue;
        dots.push({ cx: x + col * pitchX + 1.55, cy: y * pitchY + 1.55 });
      }
    });
    x += cols * pitchX + gap;
  }

  return { dots, width: x, height: 28, missing };
}
